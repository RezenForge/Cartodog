import { signup, befriend, poll, cellOf, jpeg } from '../lib.mjs';
export const title = 'Fiche d\'une balade : avis, équipements, copains, photos, Y aller';
export default async T => {
  const A = await T.dev('A'), B = await T.dev('B'), C = await T.dev('C');
  await A.route(/geo\.api\.gouv\.fr/, r => r.fulfill({ status: 200, contentType: 'application/json', body: '[{"nom":"Le Taillan-Médoc"}]' }));
  await signup(A, 'dylan@test.fr', 'Rezen', 'Dylan', 'Nova'); await signup(B, 'lea@test.fr', 'lea_33', 'Léa', 'Pistache'); await signup(C, 'tom@test.fr', 'tom', 'Tom', 'Rocky');
  await befriend(A, B, 'lea_33');
  const xy = await A.evaluate(k => balXY(k), await cellOf(A, 'Bois du Taillan'));
  await B.evaluate(x => soRpc('bal_review', { ...x, name: 'Bois du Taillan', stars: 5, body: 'Super coin ombragé', tags: ['pk', 'eau', 'ombre', 'libre'] }), xy);
  await C.evaluate(x => soRpc('bal_review', { ...x, name: 'Bois du Taillan', stars: 4, body: 'Parking un peu petit.', tags: ['pk', 'laisse'] }), xy);
  await B.evaluate(x => soRpc('bal_visit', { ...x, d: new Date(Date.now() - 864e5).toISOString().slice(0, 10) }), xy);
  const ph = await jpeg(A, 'NOVA'); await A.evaluate(async ([k, d]) => { await pPut('phA', d); D.cells[k].ph.push({ id: 'phA', d: today() }); save(); }, [await cellOf(A, 'Bois du Taillan'), ph]);
  await poll(A);
  let opened = ''; await A.exposeFunction('__open', u => { opened = u; }); await A.evaluate(() => { window.open = u => { __open(u); return null; }; });
  await A.evaluate(k => select(k), await cellOf(A, 'Bois du Taillan')); await A.waitForTimeout(1500);
  const txt = await A.evaluate(() => $('#panel').innerText);
  T.ok(txt.includes('Bois du Taillan'), 'nom de la balade'); T.ok(txt.includes('Le Taillan-Médoc'), 'commune');
  T.ok(/4,5\s*2 avis/.test(txt.replace(/\n/g, ' ')), 'note moyenne et nombre d\'avis', txt.slice(0, 200));
  T.ok(txt.includes('Parking') && txt.includes('Eau potable'), 'équipements signalés');
  T.ok(txt.includes('Léa') && txt.includes('hier'), 'copine venue récemment');
  T.ok(!txt.includes('Notes'), 'plus d\'onglet Notes');
  T.ok(await A.evaluate(() => !!document.querySelector('#bpph [data-bpo] img[src]')), 'ma photo affichée');
  await A.click('#panel [data-star="4"]'); await A.waitForTimeout(400); await A.fill('#bprvt', 'Très calme le matin'); await A.click('#panel [data-act="rvsend"]'); await A.waitForTimeout(600);
  T.ok(T.S.db.revs.some(r => r.u === 'u1' && r.stars === 4 && r.body === 'Très calme le matin'), 'mon avis envoyé');
  await A.click('#panel [data-act="amed"]'); await A.click('#panel [data-am="grande"]'); await A.waitForTimeout(400); await A.click('#panel [data-am="tpetite"]'); await A.waitForTimeout(600);
  T.eq(T.S.db.revs.find(r => r.u === 'u1').tags, ['tpetite'], 'une seule durée à la fois');
  await A.click('#panel [data-act="amok"]');
  await A.click('#panel [data-act="maps"]'); await A.waitForTimeout(200);
  T.ok(/^https:\/\/www\.google\.com\/maps\/dir\/\?api=1&destination=[-\d.]+,[-\d.]+$/.test(opened), 'Y aller ouvre Google Maps', opened);
  await A.click('#panel .bpfp'); await A.waitForTimeout(500);
  T.ok(await A.evaluate(() => !$('#pfsh').hidden), 'toucher un copain ouvre son profil');
};
